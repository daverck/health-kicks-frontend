/**
 * Generates smooth synthetic IMU accelerometer and gyroscope readings for session inspection.
 */
export function generateMockSessionReadings(
  sessionId: string,
  deviceId: string,
  label: string,
  sampleCount = 60
): StudioSessionReadingsResponse {
  const readings: ImuReading[] = [];
  const baseEpochUs = 1732635000000000; // 2026-11-26T15:30:00.000Z in microseconds
  const intervalUs = 50000; // 50ms interval (20 Hz)

  for (let i = 0; i < sampleCount; i++) {
    const t = i * 0.15;
    const epochUs = baseEpochUs + i * intervalUs;
    const dateIso = new Date(Math.floor(epochUs / 1000)).toISOString();

    readings.push({
      timestamp_epoch_us: epochUs,
      timestamp_iso: dateIso,
      ax: Number((Math.sin(t) * 0.85 + 0.1).toFixed(4)),
      ay: Number((Math.cos(t * 1.2) * 0.95 - 0.05).toFixed(4)),
      az: Number((Math.sin(t * 0.5) * 0.35 + 0.98).toFixed(4)),
      gx: Number((Math.cos(t * 0.8) * 45.2).toFixed(2)),
      gy: Number((Math.sin(t * 1.1) * 32.8).toFixed(2)),
      gz: Number((Math.cos(t * 1.4) * 18.5).toFixed(2)),
      session_id: sessionId,
      label,
    });
  }

  return {
    device_id: deviceId,
    session_id: sessionId,
    label,
    sample_count: readings.length,
    readings,
  };
}
